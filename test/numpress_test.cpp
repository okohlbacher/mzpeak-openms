/******************************************************************************/
// Real-data validation: decode the extracted m/z bytes and compare to the
// values reconstructed by the Rust reference.  Numpress-linear is lossy to
// roughly 1 / (2 * fixedPoint); a 1e-4 absolute tolerance on m/z is well
// inside that and matches what the codec guarantees for this data.

BOOST_AUTO_TEST_CASE(decode_linear_real_data)
{
  std::vector<double> mz = MzPeak::Util::numpress_decode_linear(kMzBytes);

  BOOST_REQUIRE_EQUAL(mz.size(), kMzExpected.size());
  double max_abs = 0.0;
  for (std::size_t i = 0; i < mz.size(); ++i) {
    double d = std::abs(mz[i] - kMzExpected[i]);
    if (d > max_abs) max_abs = d;
    BOOST_TEST(d < 1e-4, "m/z mismatch at " << i << ": got " << mz[i] << " expected "
                                            << kMzExpected[i] << " (delta " << d
                                            << ")");
  }
  BOOST_TEST_MESSAGE("linear max abs m/z error: " << max_abs);
}

/******************************************************************************/
// Real-data validation: decode the extracted intensity bytes (numpress-slof)
// and compare to the Rust reference.  SLOF stores a 2-byte log, so error is
// relative (~0.05%).  We assert 1e-3 relative; zero intensities must round-trip
// exactly to zero.

BOOST_AUTO_TEST_CASE(decode_slof_real_data)
{
  std::vector<float> inten = MzPeak::Util::numpress_decode_slof(kIntensityBytes);

  BOOST_REQUIRE_EQUAL(inten.size(), kIntensityExpected.size());
  double max_rel = 0.0;
  for (std::size_t i = 0; i < inten.size(); ++i) {
    float got = inten[i];
    float exp = kIntensityExpected[i];
    if (exp == 0.0f) {
      BOOST_TEST(got == 0.0f,
                 "intensity should be zero at " << i << ", got " << got);
      continue;
    }
    double rel = std::abs(static_cast<double>(got) - exp) / std::abs(exp);
    if (rel > max_rel) max_rel = rel;
    BOOST_TEST(rel < 1e-3, "intensity mismatch at " << i << ": got " << got
                                                    << " expected " << exp
                                                    << " (rel " << rel << ")");
  }
  BOOST_TEST_MESSAGE("slof max rel intensity error: " << max_rel);
}

/******************************************************************************/
// Self-contained safety net: encode a known vector with the reference
// encodeLinear, decode it back through our wrapper, and assert it round-trips
// within the linear tolerance.  Independent of any test file.

BOOST_AUTO_TEST_CASE(decode_linear_roundtrip)
{
  const std::vector<double> original = {
      100.0,      100.5,   101.0, 150.25, 200.125,
      200.250003, 300.999, 301.0, 500.5,  1000.0,
  };

  // fixedPoint chosen large enough that 1e-4 absolute round-trips comfortably.
  const double fixed_point = 1e5;
  std::vector<unsigned char> encoded;
  ms::numpress::MSNumpress::encodeLinear(original, encoded, fixed_point);

  std::vector<uint8_t> bytes(encoded.begin(), encoded.end());
  std::vector<double> decoded = MzPeak::Util::numpress_decode_linear(bytes);

  BOOST_REQUIRE_EQUAL(decoded.size(), original.size());
  for (std::size_t i = 0; i < original.size(); ++i) {
    BOOST_TEST(std::abs(decoded[i] - original[i]) < 1e-4,
               "roundtrip mismatch at " << i << ": got " << decoded[i]
                                        << " expected " << original[i]);
  }
}

